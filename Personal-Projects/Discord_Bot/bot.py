load_dotenv()

DISCORD_TOKEN = os.getenv('DISCORD_TOKEN')
GEMINI_API_KEY = os.getenv('GEMINI_API_KEY')
REQUIRED_HOURS_FOR_CERT = 400.0

gemini_client = genai.Client(api_key=GEMINI_API_KEY)

class ERPBot(commands.Bot):
    def __init__(self):
        super().__init__(command_prefix='!', intents=discord.Intents.all())

    async def setup_hook(self):
        await self.add_cog(OnboardingCog(self))
        await self.add_cog(VoiceTrackingCog(self))
        await self.add_cog(AICog(self))
        await self.add_cog(WheelCog(self))
        await self.add_cog(MusicCog(self))
        await self.tree.sync()
        print("Bot is ready and commands are synced!")

class ApplicationModal(discord.ui.Modal, title='Server Registration'):
    is_campus = discord.ui.TextInput(
        label='Are you from Belgium Campus? (Yes/No)',
        placeholder='Yes or No',
        required=True,
        max_length=4
    )
    genre = discord.ui.TextInput(
        label='What is your nickname genre?',
        placeholder='e.g., Household Appliances, Military, Cars',
        required=True,
        max_length=50
    )

    async def on_submit(self, interaction: discord.Interaction):
        await interaction.response.defer(ephemeral=True)
        
        is_bc = self.is_campus.value.strip().lower() in ['yes', 'y', 'yeah']
        user_genre = self.genre.value.strip()
        guild = interaction.guild
        
        role_name = "KomKol" if is_bc else "Kakmerk"
        role = discord.utils.get(guild.roles, name=role_name)
        
        ai_prompt = (
            f"Generate a single, absurd Discord nickname based on this genre: '{user_genre}'. "
            "It MUST sound like a highly specific appliance, vehicle, technical object, or weird item. "
            "Examples of the vibe: 'Hisense 1000W Microwave', 'Cowbell Intensifier 5000', "
            "'Renault Kwid 0.8 STD', 'Zeiss Winkel Microscope'. "
            "Return ONLY the generated name, nothing else. Maximum 30 characters."
        )
        
        try:
            ai_response = gemini_client.models.generate_content(
                model='gemini-3.5-flash',
                contents=ai_prompt
            )
            generated_name = ai_response.text.strip().replace('"', '')
        except Exception:
            generated_name = f"{user_genre[:10]} 3000"
            
        nickname = generated_name[:32]

        if role:
            await interaction.user.add_roles(role)
        
        try:
            await interaction.user.edit(nick=nickname)
            await interaction.followup.send(f"Welcome! You've been assigned the **{role_name}** role and your autogenerated name is **{nickname}**.")
        except discord.Forbidden:
            await interaction.followup.send(f"Welcome! You got the **{role_name}** role. (Note: My bot role is too low to change your nickname to **{nickname}** automatically. Ensure my bot role is higher than yours in the server settings!).")

