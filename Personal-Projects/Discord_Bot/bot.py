class VoiceTrackingCog(commands.Cog):
    def __init__(self, bot):
        self.bot = bot
        self.active_sessions = {} 
        self.total_time = {}      

    @commands.Cog.listener()
    async def on_voice_state_update(self, member, before, after):

        if before.channel is None and after.channel is not None:
            self.active_sessions[member.id] = datetime.now()
        
        elif before.channel is not None and after.channel is None:
            if member.id in self.active_sessions:
                duration = (datetime.now() - self.active_sessions[member.id]).total_seconds()
                self.total_time[member.id] = self.total_time.get(member.id, 0) + duration
                del self.active_sessions[member.id]

    @app_commands.command(name="certificate", description="Generate a certificate if you have enough VC hours")
    async def get_certificate(self, interaction: discord.Interaction):
        total_seconds = self.total_time.get(interaction.user.id, 0)
        if interaction.user.id in self.active_sessions:
            total_seconds += (datetime.now() - self.active_sessions[interaction.user.id]).total_seconds()
            
        hours = total_seconds / 3600
        
        if hours < REQUIRED_HOURS_FOR_CERT:
            await interaction.response.send_message(f"You only have {hours:.1f}/{REQUIRED_HOURS_FOR_CERT} hours. Keep chatting!", ephemeral=True)
            return

        img = Image.new('RGB', (800, 600), color=(43, 45, 49))
        draw = ImageDraw.Draw(img)
        
        draw.text((250, 150), "CERTIFICATE OF ACTIVITY", fill=(255, 215, 0), font_size=30)
        draw.text((200, 250), f"Awarded to: {interaction.user.display_name}", fill=(255, 255, 255), font_size=40)
        draw.text((280, 400), f"For completing {hours:.1f} hours of VC", fill=(200, 200, 200), font_size=20)
        
        buffer = io.BytesIO()
        img.save(buffer, format='PNG')
        buffer.seek(0)
        
        file = discord.File(buffer, filename="certificate.png")
        await interaction.response.send_message(file=file)

