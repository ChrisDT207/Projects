class WheelCog(commands.Cog):
    def __init__(self, bot):
        self.bot = bot

    @app_commands.command(name="spin", description="Spin a wheel! Separate options with commas")
    async def spin(self, interaction: discord.Interaction, options: str):
        choices = [choice.strip() for choice in options.split(',') if choice.strip()]
        if len(choices) < 2:
            await interaction.response.send_message("Please provide at least 2 options separated by commas.", ephemeral=True)
            return
            
        result = random.choice(choices)
        await interaction.response.send_message(f"🎡 **Spinning the wheel...**\n\n🎯 The wheel landed on: **{result}**!")

class MusicCog(commands.Cog):
    def __init__(self, bot):
        self.bot = bot
        self.ytdl_options = {
            'format': 'bestaudio/best',
            'noplaylist': 'True',
            'extractor-args': 'youtube:player_client=android', 
            'quiet': True,
        }
        self.ffmpeg_options = {
            'before_options': '-reconnect 1 -reconnect_streamed 1 -reconnect_delay_max 5',
            'options': '-vn',
        }
        self.ytdl = yt_dlp.YoutubeDL(self.ytdl_options)

    @app_commands.command(name="play", description="Play audio from a YouTube link")
    async def play(self, interaction: discord.Interaction, url: str):
        if not interaction.user.voice:
            await interaction.response.send_message("You must be in a voice channel first!", ephemeral=True)
            return
            
        await interaction.response.defer()
        
        channel = interaction.user.voice.channel
        voice_client = interaction.guild.voice_client
        
        if not voice_client:
            voice_client = await channel.connect()

        try:
            loop = asyncio.get_event_loop()
            data = await loop.run_in_executor(None, lambda: self.ytdl.extract_info(url, download=False))
            
            song_url = data['url']
            player = discord.FFmpegPCMAudio(song_url, **self.ffmpeg_options)
            
            if voice_client.is_playing():
                voice_client.stop()
                
            voice_client.play(player)
            await interaction.followup.send(f"🎶 Now playing: **{data.get('title')}**")
            
        except Exception as e:
            await interaction.followup.send(f"Could not play the video. YouTube may be blocking the request: {e}")

    @app_commands.command(name="stop", description="Stop the music and leave")
    async def stop(self, interaction: discord.Interaction):
        voice_client = interaction.guild.voice_client
        if voice_client:
            await voice_client.disconnect()
            await interaction.response.send_message("Disconnected.")
        else:
            await interaction.response.send_message("I'm not in a voice channel.", ephemeral=True)

